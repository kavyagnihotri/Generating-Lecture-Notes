with open('TeKnowbaseEntities.tsv') as f:
    tsv_file = csv.reader(f, delimiter="\t")
    next(tsv_file)                                            # moves onto the next row
    for name,link in tsv_file:
      if 'wikipedia' not in link:
        continue

      res = requests.get(url=link)
      soup = bs(res.content, 'html.parser')

      image = soup.select('table.infobox td.infobox-image img[src]') # images in the infobox includes vcard, vevent type
      image2 = soup.select('div.thumb.tright img[src]')       # webpages which don't have a infotable picture
      images = image + image2
      if not images:
        row = [name, link, '']                              # '' denotes no relevant images
      else:
        singleImageURL = images[0]['src']
        if 'https:' != singleImageURL[:6]:                  # maybe should check only the first
          singleImageURL = 'https:' + singleImageURL
        row = [name, link, singleImageURL]
        
      writer.writerow(row)

outputFile.close()

